const cache = new Map<string, boolean[][]>();

/** Returns the glyph as rows of booleans (true = black). Unknown chars map to "?". */
export function glyph(ch: string): boolean[][] {
  const key = ch in G ? ch : ch.toUpperCase() in G ? ch.toUpperCase() : "?";
  let g = cache.get(key);
  if (!g) {
    g = G[key].split(" ").map((row) => [...row].map((c) => c === "#"));
    cache.set(key, g);
  }
  return g;
}

export function hasGlyph(ch: string): boolean {
  return ch in G || ch.toUpperCase() in G;
}
